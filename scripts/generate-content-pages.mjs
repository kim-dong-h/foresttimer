import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTENT_UPDATED, SITE_ORIGIN, contentRoutes, sitePath } from '../src/siteRoutes.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const escape = value => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
for (const route of contentRoutes) {
  const file = `${route.path.slice(1)}index.html`;
  const relative = target => {
    const result = path.posix.relative(path.posix.dirname(file), target);
    return result.startsWith('.') ? result : `./${result}`;
  };
  const title = `${route.title} | forestTimer`;
  const html = `<!doctype html>
<!-- Generated by scripts/generate-content-pages.mjs. Edit src/siteRoutes.js for metadata. -->
<html lang="${route.language}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#213c36" />
    <meta name="description" content="${escape(route.description)}" />
    <title>${escape(title)}</title>
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="forestTimer" />
    <meta property="og:locale" content="${route.language === 'en' ? 'en_US' : 'ko_KR'}" />
    <meta property="og:title" content="${escape(title)}" />
    <meta property="og:description" content="${escape(route.description)}" />
    <meta property="og:url" content="${SITE_ORIGIN}${route.path}" />
    <link rel="canonical" href="${SITE_ORIGIN}${route.path}" />
    <link rel="alternate" hreflang="ko" href="${SITE_ORIGIN}${sitePath(route.page, 'ko')}" />
    <link rel="alternate" hreflang="en" href="${SITE_ORIGIN}${sitePath(route.page, 'en')}" />
    <link rel="alternate" hreflang="x-default" href="${SITE_ORIGIN}${sitePath(route.page, 'ko')}" />
    <link rel="icon" type="image/svg+xml" href="${relative('favicon.svg')}" />
    <script async src="https://www.googletagmanager.com/gtag/js?id=G-G2B2YQK02K"></script>
    <script>
      window.dataLayer = window.dataLayer || [];
      function gtag(){dataLayer.push(arguments);}
      gtag('js', new Date());
      gtag('config', 'G-G2B2YQK02K');
    </script>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="${relative('src/contentMain.jsx')}"></script>
  </body>
</html>
`;
  const target = path.join(root, file);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, html, 'utf8');
}

const paths = ['/', '/us/', '/percent/', '/percent/us/', '/cooking/', ...contentRoutes.map(route => route.path)];
await writeFile(path.join(root, 'public/sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${paths.map(url => `  <url><loc>${SITE_ORIGIN}${url}</loc>${contentRoutes.some(route => route.path === url) ? `<lastmod>${CONTENT_UPDATED}</lastmod>` : ''}</url>`).join('\n')}
</urlset>
`, 'utf8');
console.log(`Generated ${contentRoutes.length} content entries and sitemap.`);
